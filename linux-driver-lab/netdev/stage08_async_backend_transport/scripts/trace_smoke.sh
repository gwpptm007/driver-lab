# =============================================================================
# trace_smoke.sh — 收集 stage08 驱动的 dmesg 日志（用于快速诊断）
# =============================================================================
#
# 【学习要点】
#
# 1. dmesg 的作用
#    dmesg 打印内核环形缓冲区内容，包含了驱动在运行时打印的所有 pr_info/pr_err 等。
#    对于网络设备驱动，可以在这里看到：模块加载、接口 up/down、TX/RX 统计、错误信息等。
#
# 2. dmesg 是实时追加的
#    内核日志缓冲区是一个固定大小的环形 buffer，新的日志会覆盖旧的。
#    如果日志过多，需要在测试前清理一次 dmesg -C（清除缓冲区）或 tail -n 200 只看最新的。
#
# 3. grep -E 'stage08|netdev_stage08'
#    -E 启用扩展正则，可以同时匹配两个关键字
#    stage08 是模块名（出现在 pr_info 的前缀），netdev_stage08 是 driver name
#    两者同时匹配可以覆盖驱动中所有日志输出
#
# 4. tee 的双重输出
#    tee 把输出同时写到文件（归档）和 stdout（实时查看）
#    适用于测试脚本的日志记录
#
# 5. 为什么 tail -n 200
#    dmesg 可能输出数万行，但很多是系统启动早期的内容（与当前测试无关）
#    只看最近的 200 行能更聚焦于本次测试相关的日志
#
# =============================================================================

set -euo pipefail

# 【学习】时间戳命名：每次运行生成唯一的日志文件名
STAMP=$(date +%Y%m%d-%H%M%S)

# 【学习】默认输出文件名可通过第一个参数覆盖
# 用法：./trace_smoke.sh /tmp/my_trace.log
OUT=${1:-stage08_dmesg_${STAMP}.log}

# =============================================================================
# 核心逻辑
# =============================================================================
# 【学习】dmesg 输出格式（带时间戳时）：
#   [  123.456789] stage08 nds8: some message here
# 时间戳是相对于内核启动的时间，对分析各阶段耗时很有帮助。
# grep -E 过滤只保留与 stage08 相关的内容。
# tail -n 200 只保留最近 200 行，防止日志过多难以查看。
# tee 把日志同时写到 stdout 和文件，兼顾实时性和归档需求。
sudo dmesg | grep -E 'stage08|netdev_stage08' | tail -n 200 | tee "$OUT"

echo "[stage08] trace log -> $OUT"