#
# 【学习要点】
#
# 1. 多队列分布验证的意义
#    stage09 的核心价值之一是验证"流量被分散到多个队列"
#    如果只有一个队列活跃，说明队列分发策略有问题（单队列退化为 stage08）
#
# 2. 差分验证 vs 直接读取
#    直接读取 stats：包含历史累计，干扰大
#    差分验证（before/after 快照相减）：只关心本次测试的增量
#
# 3. grep -E '^q[0-9]+: .*tx_submit=[1-9][0-9]*' 解析逻辑
#    - 匹配 q0: ... tx_submit=N 或 q1: ... tx_submit=N 格式
#    - tx_submit=[1-9][0-9]*：第一位非 0（排除历史 0 值）
#    - active_queues = 匹配的行数 = 有实际发帧的队列数
#
# 4. 通过阈值
#    - hits >= 2：至少 2 个队列有 tx_submit（多队列证明）
#    - hits < 2：说明分发策略有问题（退化为单队列）
#
# 5. 与 stage08 的本质差异
#    stage08 只有单队列 q0，不会出现 q1
#    stage09 如果分发正常，应该有 >= 2 个队列同时活跃
#
